"""Generate code and shapes from the LinkML schema (DESIGN section 6).

The schema in schema/ is the single source of truth. This writes:

    src/ckg/generated/model.py          Pydantic models
    schema/generated/ckg.schema.json    JSON Schema
    schema/generated/ckg.shacl.ttl      SHACL shapes
    schema/generated/ckg.owl.ttl        OWL ontology

Do not hand-edit the outputs. Rerun after any schema change:

    uv run python tools/gen_schema.py           # write the files
    uv run python tools/gen_schema.py --check   # fail if any are stale

SHACL shapes are generated open (not closed), so nodes may carry triples
beyond the schema's slots; domain and range checks still apply.
"""

from __future__ import annotations

import argparse
import re
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema" / "domain.yaml"
HEADER = "Generated by tools/gen_schema.py from schema/domain.yaml. Do not edit."

# Generators add the current time; drop it so output only changes when the schema does.
TIMESTAMP_LINES = re.compile(r"^.*(generation_date|generated_at|Auto generated from .* by|dcterms:modified).*\n", re.M)


def generate() -> dict[Path, str]:
    warnings.filterwarnings("ignore")
    from linkml.generators.jsonschemagen import JsonSchemaGenerator
    from linkml.generators.owlgen import OwlSchemaGenerator
    from linkml.generators.pydanticgen import PydanticGenerator
    from linkml.generators.shaclgen import ShaclGenerator

    schema = str(SCHEMA)
    outputs = {
        ROOT / "src/ckg/generated/model.py": ("#", PydanticGenerator(schema).serialize()),
        ROOT / "schema/generated/ckg.schema.json": (None, JsonSchemaGenerator(schema, top_class="KnowledgeGraph").serialize()),
        ROOT / "schema/generated/ckg.shacl.ttl": ("#", ShaclGenerator(schema, closed=False).serialize()),
        ROOT / "schema/generated/ckg.owl.ttl": ("#", OwlSchemaGenerator(
            schema,
            skip_vacuous_local_range_axioms=True,
            skip_vacuous_min_zero_cardinality_axioms=True,
            consolidate_cardinality_axioms=True,
            skip_abstract_class_as_unionof_subclasses=True,
        ).serialize()),
    }
    result = {}
    for path, (comment, text) in outputs.items():
        text = TIMESTAMP_LINES.sub("", text).rstrip() + "\n"
        if comment:
            text = f"{comment} {HEADER}\n" + text
        result[path] = text
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated file is missing or stale")
    args = parser.parse_args()

    stale = []
    for path, text in generate().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'}: {path.relative_to(ROOT).as_posix()}")
    if not stale:
        print("generated files are up to date")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
